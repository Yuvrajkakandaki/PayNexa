import mongoose from "mongoose";

const invoiceSchema = new mongoose.Schema(
  {
    clientName: {
      type: String,
      required: [true, "Customer name is required."],
      trim: true,
      maxlength: [100, "Customer name cannot exceed 100 characters."],
    },

    clientEmail: {
      type: String,
      required: [true, "Customer email is required."],
      trim: true,
      lowercase: true,
      maxlength: [254, "Customer email is too long."],
      match: [
        /^[^\s@]+@[^\s@]+\.[^\s@]+$/,
        "Please provide a valid customer email.",
      ],
    },

    items: {
      type: [
        {
          name: {
            type: String,
            required: [true, "Item name is required."],
            trim: true,
            maxlength: [200, "Item name cannot exceed 200 characters."],
          },

          quantity: {
            type: Number,
            required: [true, "Item quantity is required."],
            min: [1, "Item quantity must be at least 1."],
            validate: {
              validator: Number.isFinite,
              message: "Item quantity must be a finite number.",
            },
          },

          unitPrice: {
            type: Number,
            required: [true, "Item unit price is required."],
            min: [0, "Item unit price cannot be negative."],
            validate: {
              validator: Number.isFinite,
              message: "Item unit price must be a finite number.",
            },
          },
        },
      ],
      validate: [
        {
          validator: (items) => items.length > 0,
          message: "An invoice must contain at least one item.",
        },
        {
          validator: (items) =>
            items.every(
              (item) =>
                Number.isInteger(item.quantity) &&
                item.quantity > 0 &&
                Number.isFinite(item.unitPrice) &&
                item.unitPrice >= 0
            ),
          message: "Invoice items contain invalid quantities or prices.",
        },
      ],
    },

    currency: {
      type: String,
      required: true,
      default: "USD",
      uppercase: true,
      trim: true,
      match: [
        /^[A-Z]{3}$/,
        "Currency must be a three-letter currency code.",
      ],
    },

    dueDate: {
      type: Date,
      required: [true, "Invoice due date is required."],
      validate: {
        validator: (value) =>
          value instanceof Date && !Number.isNaN(value.getTime()),
        message: "Please provide a valid invoice due date.",
      },
    },

    // paypalInvoiceId is null while status is "creating" or "failed",
    // so it is optional here and validated at the application layer.
    // partialFilterExpression guarantees multiple null/missing values are never indexed.
    paypalInvoiceId: {
      type: String,
      trim: true,
      index: {
        unique: true,
        partialFilterExpression: { paypalInvoiceId: { $type: "string" } },
      },
    },

    status: {
      type: String,
      required: true,
      default: "creating",
      uppercase: true,
      trim: true,
      enum: {
        values: [
          // Transient states (set by our backend)
          "CREATING",  // placeholder written before PayPal is called
          "FAILED",    // PayPal call failed; user may retry with new requestId

          // PayPal states
          "DRAFT",
          "SENT",
          "SCHEDULED",
          "PAID",
          "PARTIALLY_PAID",
          "UNPAID",
          "CANCELLED",
          "VOID",
          "REFUNDED",
          "MARKED_AS_PAID",
        ],
        message: "Invalid invoice status: {VALUE}.",
      },
    },

    idempotencyKey: {
      type: String,
      trim: true,
      index: {
        unique: true,
        partialFilterExpression: { idempotencyKey: { $type: "string" } },
      },
    },

    // requestId is generated by the frontend (crypto.randomUUID) when the
    // user opens the confirm card. It prevents double-submissions on the
    // same form open even if the server is slow to respond.
    requestId: {
      type: String,
      trim: true,
      index: {
        unique: true,
        partialFilterExpression: { requestId: { $type: "string" } },
      },
    },

    // Multi-tenant user reference (Task 3.5)
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      index: true,
    },
  },
  {
    timestamps: true,
  }
);

// Compound index for efficient user-scoped queries and pagination (Task 4.5)
invoiceSchema.index({ userId: 1, createdAt: -1 });

const Invoice = mongoose.model("Invoice", invoiceSchema);

export default Invoice;